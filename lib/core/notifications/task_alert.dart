  /// its card, and asking «قعدت على الموبايل؟» would be Nouri nagging about
  /// something it has no business policing.
  final Duration? followUpAfter;

  final String? followUpQuestion;
}

/// Every task id that can carry an alarm, in a **fixed, append-only order**.
///
/// The order is load-bearing: `taskAlarmId` uses the index, so inserting into
/// the middle would renumber alarms already sitting in AlarmManager. Append
/// only, exactly like [NotificationSlot].
///
/// It is keyed on the *task* rather than the alert kind because several tasks
/// share a kind — both meals, and all three faces of knowledge time. Keying
/// the id on the kind gave أول وجبة and آخر وجبة the same id, so the later one
/// silently overwrote the earlier and the first meal of the day was never
/// announced. Found by a test asserting ids are unique.
const alarmableTaskIds = <String>[
  'morning-athkar',
  'evening-athkar',
  'sleep-athkar',
  'tasbeeh',
  'quran-wird',
  'first-meal',
  'last-meal',
  'walk',
  'workout',
  'knowledge-read',
  'knowledge-listen',
  'knowledge-skill',
  'calls',
  'phone-time',
];

/// The alert a planned task should sound with, or null when it has none.
///
/// The ids are the ones `dailyTasksFor` emits. A task the planner places but
/// that maps to nothing here would arrive silent, which is the one outcome
/// this whole slice exists to prevent — so a test walks every id.
TaskAlertKind? alertKindForTaskId(String taskId) => switch (taskId) {
      'morning-athkar' => TaskAlertKind.athkarMorning,
      'evening-athkar' => TaskAlertKind.athkarEvening,
      'sleep-athkar' => TaskAlertKind.athkarSleep,
      'tasbeeh' => TaskAlertKind.tasbeeh,
      'quran-wird' => TaskAlertKind.wird,
      'first-meal' || 'last-meal' => TaskAlertKind.meal,
      'walk' => TaskAlertKind.walk,
      // The planner does not place a workout yet — البدن → تمارين البيت is
      // opened by hand. The kind exists so that when it does, it already has
      // a sound of its own rather than borrowing the walk's.
      'workout' => TaskAlertKind.workout,
      'knowledge-read' ||
      'knowledge-listen' ||
      'knowledge-skill' =>
        TaskAlertKind.knowledge,
      'calls' => TaskAlertKind.calls,
      'phone-time' => TaskAlertKind.phone,
      _ => null,
    };

/// One row per thing Nouri can call you about, and everything about it.
///
/// **Android ties a notification's sound to its channel, not to the
/// notification.** That single fact shapes this file: "a different sound for
/// every task" means "a channel for every task", so each kind below owns a
/// channel id, a raw sound resource, its copy, where tapping it goes, and
/// whether it asks afterwards.
///
/// Keeping all of that in one enum is the point. A new kind of alert is one
/// entry here rather than five edits spread across the scheduler, the channel
/// list, the route parser and the copy.
///
/// The user's reason for wanting this, in their own words: *"i don't need to
/// open the app to know what i have to do ... from alarms i know what this
/// task."* So no two kinds may share a sound, and a test enforces it.
library;

